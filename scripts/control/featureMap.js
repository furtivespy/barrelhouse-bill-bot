// Feature Map: every slash command, generated from the live command
// definitions, plus hand-written seed-and-reach notes (docs/feature-map/notes.md).
//
//   INDEX.md  generated; `map --write` rewrites it, `map --check` fails on drift
//   notes.md  hand-written; one `## /command` section per slash command

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { ApplicationCommandOptionType } from "discord.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..", "..");
const SLASH_ROOT = path.join(ROOT, "src", "commands", "slash");
const TEST_ROOT = path.join(ROOT, "tests");
const MAP_DIR = path.join(ROOT, "docs", "feature-map");
const INDEX_PATH = path.join(MAP_DIR, "INDEX.md");
const NOTES_PATH = path.join(MAP_DIR, "notes.md");

const STUB_CLIENT = {
  logger: { info: () => {}, warn: () => {}, error: () => {}, log: () => {} },
  config: {},
};

function posix(p) {
  return p.split(path.sep).join("/");
}

function readText(file) {
  return fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
}

function walk(dir, extension) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full, extension));
    else if (entry.name.endsWith(extension)) files.push(full);
  }
  return files.sort();
}

function subcommandsOf(json) {
  const out = [];
  for (const option of json.options || []) {
    if (option.type === ApplicationCommandOptionType.SubcommandGroup) {
      for (const sub of option.options || []) {
        out.push({ path: `${option.name} ${sub.name}`, description: sub.description });
      }
    } else if (option.type === ApplicationCommandOptionType.Subcommand) {
      out.push({ path: option.name, description: option.description });
    }
  }
  return out;
}

async function describeCommand(file, { testFiles, stubClient = STUB_CLIENT }) {
  const mod = await import(pathToFileURL(file).href);
  const Command = mod.default || mod;
  const command = new Command(stubClient);
  const json = command.data.toJSON();
  const rel = posix(path.relative(ROOT, file));
  const importNeedle = rel.replace(/^src\//, "");
  const tests = testFiles
    .filter((t) => t.text.includes(importNeedle))
    .map((t) => t.rel)
    .sort();
  return {
    name: json.name,
    description: json.description,
    source: rel,
    permLevel: command.conf?.permLevel ?? command.help?.permLevel ?? "User",
    subcommands: subcommandsOf(json),
    tests,
  };
}

let cachedCommands = null;

async function loadCommands({ refresh = false, stubClient } = {}) {
  if (cachedCommands && !refresh) return cachedCommands;
  const testFiles = walk(TEST_ROOT, ".test.js").map((file) => ({
    rel: posix(path.relative(ROOT, file)),
    text: readText(file),
  }));
  const files = walk(SLASH_ROOT, ".js");
  const loaded = [];
  for (const file of files) {
    loaded.push(await describeCommand(file, { testFiles, stubClient }));
  }
  cachedCommands = loaded.sort((a, b) => a.name.localeCompare(b.name));
  return cachedCommands;
}

function renderEntry(command) {
  const lines = [
    `## /${command.name}`,
    "",
    command.description,
    "",
    `- Source: \`${command.source}\``,
    `- Permission: ${command.permLevel}`,
    `- Tests: ${command.tests.length ? command.tests.map((t) => `\`${t}\``).join(", ") : "none"}`,
  ];
  if (command.subcommands.length) {
    lines.push(
      `- Subcommands: ${command.subcommands.map((s) => `\`${s.path}\``).join(", ")}`
    );
  }
  return lines.join("\n");
}

function renderIndex(commands) {
  return [
    "# Feature Map",
    "",
    "<!-- Generated by `bun run control map --write` from the slash-command definitions. Do not edit by hand: `bun run control map --check` (and `bun test`) fail when this drifts. Seed-and-reach notes are hand-written in notes.md. -->",
    "",
    commands.map(renderEntry).join("\n\n"),
    "",
  ].join("\n");
}

function parseNotes(text) {
  const sections = new Map();
  const parts = text.split(/^## \/(\S+)[ \t]*$/m);
  for (let i = 1; i < parts.length; i += 2) {
    sections.set(parts[i], parts[i + 1].trim());
  }
  return sections;
}

// `/cmd sub` references inside backticks must name a real subcommand when the
// command has any. The second word is only checked after a subcommand group.
function referenceProblems(name, body, command) {
  if (!command.subcommands.length) return [];
  const problems = [];
  const known = new Set(command.subcommands.map((s) => s.path));
  const groups = new Set(
    command.subcommands
      .filter((s) => s.path.includes(" "))
      .map((s) => s.path.split(" ")[0])
  );
  for (const span of body.matchAll(/`\/([\w-]+)((?: [\w-]+(?::\S*)?)*)[^`]*`/g)) {
    if (span[1] !== name) continue;
    const words = span[2]
      .trim()
      .split(" ")
      .filter((w) => w && !w.includes(":"));
    if (!words.length) continue;
    const [first, second] = words;
    const ok = groups.has(first)
      ? second === undefined || known.has(`${first} ${second}`)
      : known.has(first);
    if (!ok) {
      problems.push(
        `notes.md mentions \`${span[0].slice(1, -1)}\`, but /${name} has no subcommand \`${groups.has(first) && second ? `${first} ${second}` : first}\``
      );
    }
  }
  return problems;
}

function checkFeatureMap({ commands, index, notes }) {
  const problems = [];
  const expected = renderIndex(commands);
  if (index.replace(/\r\n/g, "\n") !== expected) {
    problems.push(
      "docs/feature-map/INDEX.md is out of date. Run `bun run control map --write` and commit it."
    );
  }
  const sections = parseNotes(notes.replace(/\r\n/g, "\n"));
  const byName = new Map(commands.map((c) => [c.name, c]));
  for (const command of commands) {
    if (!sections.has(command.name)) {
      problems.push(
        `No note for /${command.name}. Add a "## /${command.name}" section with Seed and Reach lines to docs/feature-map/notes.md.`
      );
    }
  }
  for (const [name, body] of sections) {
    const command = byName.get(name);
    if (!command) {
      problems.push(
        `docs/feature-map/notes.md has a section for /${name}, which is not a slash command. Remove or rename it.`
      );
      continue;
    }
    for (const label of ["Seed", "Reach"]) {
      if (!new RegExp(`^- ${label}: \\S`, "m").test(body)) {
        problems.push(`The note for /${name} needs a "- ${label}: ..." line.`);
      }
    }
    problems.push(...referenceProblems(name, body, command));
  }
  return problems;
}

function readMapFiles() {
  return {
    index: fs.existsSync(INDEX_PATH) ? readText(INDEX_PATH) : "",
    notes: fs.existsSync(NOTES_PATH) ? readText(NOTES_PATH) : "",
  };
}

async function writeIndex(commands) {
  const list = commands || (await loadCommands({ refresh: true }));
  fs.mkdirSync(MAP_DIR, { recursive: true });
  fs.writeFileSync(INDEX_PATH, renderIndex(list));
  return INDEX_PATH;
}

async function check(commands) {
  const list = commands || (await loadCommands({ refresh: true }));
  return checkFeatureMap({ commands: list, ...readMapFiles() });
}

async function describeFeature(name, commands) {
  const list = commands || (await loadCommands());
  const wanted = name.replace(/^\//, "");
  const command = list.find((c) => c.name === wanted);
  if (!command) return null;
  const note = parseNotes(readMapFiles().notes).get(wanted);
  return `${renderEntry(command)}\n\n${note ? `Notes:\n${note}` : "Notes: none yet."}\n`;
}

export {
  INDEX_PATH,
  NOTES_PATH,
  check,
  checkFeatureMap,
  describeFeature,
  loadCommands,
  parseNotes,
  renderIndex,
  writeIndex,
};
